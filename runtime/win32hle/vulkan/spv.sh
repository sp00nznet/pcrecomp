#!/bin/sh
# The SPIR-V d3d_vulkan.c carries (../d3d_vulkan_spv.h), from these shaders:
# run after changing one (glslangValidator and spirv-val: Homebrew's glslang
# and spirv-tools, or the Vulkan SDK's).
set -e
cd "$(dirname "$0")"
out=../d3d_vulkan_spv.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
echo "/* Generated by vulkan/spv.sh from the shaders in vulkan/: do not edit. */" > "$tmp/all.h"
for f in d3d.vert d3d.frag clear.frag blit.frag pack.comp unpack.comp; do
  n=spv_$(echo "$f" | tr . _)
  glslangValidator -V --target-env vulkan1.3 --vn "$n" -o "$tmp/$n.h" "$f" >/dev/null
  glslangValidator -V --target-env vulkan1.3 -o "$tmp/$n.spv" "$f" >/dev/null
  spirv-val --target-env vulkan1.3 "$tmp/$n.spv"
  grep -v -e '^[[:space:]]*//' -e '#pragma once' "$tmp/$n.h" | sed 's/^const uint32_t/static const uint32_t/' >> "$tmp/all.h"
done
mv "$tmp/all.h" "$out"
echo "$out"
