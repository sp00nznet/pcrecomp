#!/bin/sh
# The SPIR-V d3d_vulkan.c carries (../d3d_vulkan_spv.h), from these shaders:
# run after changing one (glslangValidator and spirv-val: Homebrew's glslang
# and spirv-tools, or the Vulkan SDK's).
#
# The SPIR-V is glslang's output, which can change between its versions, so
# the header in the tree was made with GLSLANG below and regenerating it with
# that version gives the same bytes. Another version is refused, unless
# SPV_ANY_GLSLANG=1 (then the header names the version it was made with).
GLSLANG=16.6.0
set -e
cd "$(dirname "$0")"
have=$(glslangValidator --version | sed -n 's/^Glslang Version: [0-9]*://p')
if [ "$have" != "$GLSLANG" ]; then
  if [ "${SPV_ANY_GLSLANG:-0}" = 1 ]; then
    echo "spv.sh: glslang $have, not $GLSLANG: the SPIR-V may differ from the tree's" >&2
  else
    echo "spv.sh: needs glslang $GLSLANG (this is ${have:-not found}); SPV_ANY_GLSLANG=1 to use it anyway" >&2
    exit 1
  fi
fi
out=../d3d_vulkan_spv.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
echo "/* Generated by vulkan/spv.sh from the shaders in vulkan/, with glslang $have: do not edit. */" > "$tmp/all.h"
for f in d3d.vert d3d.frag clear.frag blit.frag pack.comp unpack.comp; do
  n=spv_$(echo "$f" | tr . _)
  glslangValidator -V --target-env vulkan1.3 --vn "$n" -o "$tmp/$n.h" "$f" >/dev/null
  glslangValidator -V --target-env vulkan1.3 -o "$tmp/$n.spv" "$f" >/dev/null
  spirv-val --target-env vulkan1.3 "$tmp/$n.spv"
  grep -v -e '^[[:space:]]*//' -e '#pragma once' "$tmp/$n.h" | sed 's/^const uint32_t/static const uint32_t/' >> "$tmp/all.h"
done
mv "$tmp/all.h" "$out"
echo "$out"
